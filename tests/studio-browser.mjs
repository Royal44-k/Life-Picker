import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdir,writeFile,readFile} from 'node:fs/promises';
import {unzipSync} from 'fflate';
const browser=await chromium.launch({channel:'msedge',headless:true});
const context=await browser.newContext({viewport:{width:390,height:844}});
const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
const base=process.env.TEST_URL||'http://localhost:5173';
await mkdir('artifacts',{recursive:true});
try{
 await page.goto(base);await page.getByRole('heading',{name:'把经历，编成作品。'}).waitFor();
 assert.ok(await page.getByRole('button',{name:'新建作品',exact:true}).isVisible());
 await page.getByRole('button',{name:'新建作品',exact:true}).click();
 await page.getByLabel('作品原文').fill('# 我的真实经历\n\n## 第一次\n\n这是我自己写下的第一段。\n\n---\n\n## 后来\n\n另一段真实记录。');
 await page.getByRole('button',{name:'生成分镜',exact:true}).click();
 await page.getByRole('tab',{name:'分镜',exact:true}).click();
 await page.getByRole('button',{name:'编辑第 2 页'}).click();
 await page.getByLabel('本页文字').fill('这一句是手动修改，必须保留 ✨');
 await page.getByRole('button',{name:'锁定本页',exact:true}).click();
 await page.getByRole('button',{name:'保存并关闭',exact:true}).click();
 await page.getByText('已保存到本机',{exact:true}).waitFor();
 await page.reload();await page.getByRole('tab',{name:'分镜',exact:true}).click();
 await page.getByRole('button',{name:'编辑第 2 页'}).click();
 assert.equal(await page.getByLabel('本页文字').inputValue(),'这一句是手动修改，必须保留 ✨');
 assert.ok(await page.getByLabel('本页文字').isDisabled());
 await page.getByRole('button',{name:'保存并关闭',exact:true}).click();
 const image=await page.evaluate(()=>{const c=document.createElement('canvas');c.width=500;c.height=300;const x=c.getContext('2d');x.fillStyle='#137565';x.fillRect(0,0,500,300);return c.toDataURL('image/png').split(',')[1];});
 await page.getByRole('tab',{name:'素材',exact:true}).click();
 await page.getByLabel('上传照片').setInputFiles({name:'我的照片.png',mimeType:'image/png',buffer:Buffer.from(image,'base64')});
 await page.getByText('我的照片.png',{exact:true}).waitFor();
 await page.getByRole('button',{name:'用作封面照片'}).first().click();
 await page.getByText('已保存到本机',{exact:true}).waitFor();
 await page.getByRole('tab',{name:'预览',exact:true}).click();
 await page.locator('.scene-preview canvas').first().waitFor();
 const downloadPromise=page.waitForEvent('download');
 await page.getByRole('button',{name:'整篇 ZIP',exact:true}).click();
 const zipDownload=await downloadPromise;const entries=unzipSync(await readFile(await zipDownload.path()));
 assert.ok(Object.keys(entries).some(k=>k.endsWith('.png')));
 const p=Object.values(entries)[0];assert.equal(new DataView(p.buffer,p.byteOffset).getUint32(16),1080);
 const backupPromise=page.waitForEvent('download');
 await page.getByRole('button',{name:'备份作品',exact:true}).click();
 const backup=await backupPromise;const backupBytes=await readFile(await backup.path());const bundle=unzipSync(backupBytes);
 const manifest=JSON.parse(new TextDecoder().decode(bundle['manifest.json']));
 assert.ok(manifest.story.pages.some(p=>p.source.includes('手动修改')));
 assert.ok(Object.keys(bundle).some(k=>k.startsWith('media/')));
 await page.screenshot({path:'artifacts/shiye-1.1-mobile.png',fullPage:true});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 assert.deepEqual(errors,[]);
 console.log('PASS mobile storyboard edit/lock/reload, photo import, scene export, backup and overflow');
 await writeFile('artifacts/studio-results.json',JSON.stringify({passed:true,errors,viewport:'390x844, Chromium; not real iPhone'},null,2));
}finally{await browser.close();}
